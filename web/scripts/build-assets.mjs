// Generates engine/assets.js from the Python package (single source of truth):
// the runtime wrapper and the SCORM 2004 schema files. Run: node scripts/build-assets.mjs
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, dirname } from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const kit = join(here, '..', '..', 'scormkit');
const walk = d => readdirSync(d).flatMap(n => statSync(join(d, n)).isDirectory() ? walk(join(d, n)) : [join(d, n)]);
const schemaDir = join(kit, 'schema-2004');
const schema = Object.fromEntries(walk(schemaDir).sort().map(f => [relative(schemaDir, f).split('\\').join('/'), readFileSync(f, 'utf8')]));
const tpl = JSON.parse(execFileSync('python3', ['-c',
  'import json,sys; sys.path.insert(0, sys.argv[1]); from scormkit import templates as t; ' +
  'print(json.dumps({k: getattr(t, k) for k in ["BASE_CSS","ICON_CHECK","ICON_OPEN","TEST_BANNER","RESUME_DIALOG","MEDIA_SCRIPT","PDF_SCRIPT"]}))',
  join(kit, '..')]).toString());
const out = `// GENERATED by scripts/build-assets.mjs from ../scormkit. Do not edit by hand.
export const WRAPPER_JS = ${JSON.stringify(readFileSync(join(kit, 'wrapper.js'), 'utf8'))};
export const SCHEMA_2004 = ${JSON.stringify(schema)};
export const TPL = ${JSON.stringify(tpl)};
`;
writeFileSync(join(here, '..', 'public', 'engine', 'assets.js'), out);
console.log(`public/engine/assets.js written (${Object.keys(schema).length} schema files, ${(out.length / 1024).toFixed(0)} KB)`);
